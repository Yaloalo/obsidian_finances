import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { readFileSync } from "node:fs";
import { compile, preprocess } from "svelte/compiler";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Obsidian Finances Pipeline Plugin
*/
`;

const prod = process.argv[2] === "production";

const sveltePlugin = {
	name: "svelte5-esbuild",
	setup(build) {
		build.onLoad({ filter: /\.svelte$/ }, async (args) => {
			const source = readFileSync(args.path, "utf8");
			const preprocessed = await preprocess(source, {
				script: async ({ content, attributes }) => {
					if (attributes.lang === "ts") {
						const res = await esbuild.transform(content, {
							loader: "ts",
							target: "es2020",
							tsconfigRaw: {
								compilerOptions: {
									verbatimModuleSyntax: true
								}
							}
						});
						return { code: res.code };
					}
					return { code: content };
				}
			});
			const compiled = compile(preprocessed.code, {
				filename: args.path,
				generate: "client",
				css: "injected"
			});
			return {
				contents: compiled.js.code,
				loader: "js"
			};
		});
	}
};

const context = await esbuild.context({
	banner: {
		js: banner
	},
	entryPoints: ["main.ts"],
	bundle: true,
	plugins: [sveltePlugin],
	conditions: ["svelte", "browser", "import", "default"],
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins
	],
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: false,
	treeShaking: true,
	outfile: "main.js",
	minify: prod
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
